-- ---------------------------------------------------------------
-- 2. Свободные комнаты на период с учётом вместимости
-- Условие пересечения интервалов: начало_1 < конец_2 AND конец_1 > начало_2
-- ---------------------------------------------------------------
SELECT r.id, r.name, r.floor, r.capacity
FROM rooms r
WHERE r.is_active
  AND r.capacity >= 5                                   -- число участников
  AND NOT EXISTS (
        SELECT 1
        FROM bookings b
        WHERE b.room_id = r.id
          AND b.status = 'confirmed'
          AND b.starts_at < '2026-11-16 10:30+03'       -- конец запрошенного периода
          AND b.ends_at   > '2026-11-16 10:00+03'       -- начало запрошенного периода
  )
ORDER BY r.capacity, r.name;

-- ---------------------------------------------------------------
-- 3. Создание брони
-- Пересечения отсекает ограничение no_overlapping_bookings.
-- При конфликте PostgreSQL вернёт SQLSTATE 23P01 (exclusion_violation), приложение превращает его в ответ "комната занята" (HTTP 409).
-- ---------------------------------------------------------------
INSERT INTO bookings (room_id, user_id, title, starts_at, ends_at)
VALUES (3, 2, 'Ретро команды', '2026-11-17 15:00+03', '2026-11-17 16:00+03')
RETURNING id, status;

-- ---------------------------------------------------------------
-- 4. Отмена брони (только автором или админом, проверяется в приложении)
-- Запись не удаляется, чтобы сохранялась история.
-- ---------------------------------------------------------------
UPDATE bookings
SET status = 'cancelled', cancelled_at = now()
WHERE id = 1 AND status = 'confirmed'
RETURNING id, status, cancelled_at;

-- ---------------------------------------------------------------
-- 5. Мои предстоящие брони
-- ---------------------------------------------------------------
SELECT b.id, r.name AS room, b.title, b.starts_at, b.ends_at
FROM bookings b
JOIN rooms r ON r.id = b.room_id
WHERE b.user_id = 2
  AND b.status = 'confirmed'
  AND b.starts_at >= now()
ORDER BY b.starts_at;

-- ---------------------------------------------------------------
-- 6. Расписание комнаты на день
-- ---------------------------------------------------------------
SELECT b.starts_at, b.ends_at, b.title, u.full_name
FROM bookings b
JOIN users u ON u.id = b.user_id
WHERE b.room_id = 2
  AND b.status = 'confirmed'
  AND b.starts_at >= '2026-11-16 00:00+03'
  AND b.starts_at <  '2026-11-17 00:00+03'
ORDER BY b.starts_at;

